const LANDMARK_POIS_BY_PACK = {
  roc_1949: [],
  jp_pref: [],
  cn_prov: [],
  world_countries: []
};

for (const poi of LANDMARK_POI_DATA) {
  if (!LANDMARK_POIS_BY_PACK[poi.packId]) LANDMARK_POIS_BY_PACK[poi.packId] = [];
  LANDMARK_POIS_BY_PACK[poi.packId].push(poi);
}

function getLandmarkPoisForPack(packId) {
  return LANDMARK_POIS_BY_PACK[packId] || [];
}

function getLandmarkTopicLabelForPack(pack) {
  if (!pack) return "地標";
  if (pack.features && pack.features.landmarkLabel) return pack.features.landmarkLabel;
  if (pack.id === "roc_1949") return "歷史地標";
  if (pack.id === "jp_pref" || pack.id === "cn_prov") return "著名地標";
  if (pack.id === "world_countries") return "世界地標";
  return "地標";
}
