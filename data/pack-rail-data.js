function _dedupeBranchStations(branches) {
  const seen = new Set();
  const merged = [];
  for (let b = 0; b < branches.length; b++) {
    const br = branches[b];
    for (let i = 0; i < br.length; i++) {
      const st = br[i];
      if (!seen.has(st[0])) {
        seen.add(st[0]);
        merged.push(st);
      }
    }
  }
  return merged;
}

