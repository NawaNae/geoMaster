// Fast O(1) lookup by `${packId}::${stationName}` for parentItemId, countyName, aliases, lat/lng
const PACK_RAIL_STATION_META = {};
Object.keys(PACK_RAIL_LINES).forEach((packId) => {
  const lines = PACK_RAIL_LINES[packId] || [];
  lines.forEach((line) => {
    (line.stations || []).forEach((st) => {
      const key = `${packId}::${st[0]}`;
      if (!PACK_RAIL_STATION_META[key]) {
        PACK_RAIL_STATION_META[key] = {
          name: st[0],
          lat: st[1],
          lng: st[2],
          parentItemId: st[3],
          countyName: st[4],
          aliases: Array.isArray(st[5]) ? st[5] : []
        };
      }
    });
  });
});

function getPackRailLines(packId) {
  return PACK_RAIL_LINES[packId] || [];
}
